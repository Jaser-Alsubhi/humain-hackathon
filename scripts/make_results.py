"""Build the results tables from results/recovery_eval.json.
python scripts/make_results.py     writes docs/RESULTS.md and refreshes the block between the RESULTS markers in README.md and docs/REPORT.md
Every saved run is counted. The results file keeps only the latest run per scenario, method and model."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GROUPS = [
    ("Outages", ["db_down", "db_paused", "bad_config", "compound", "injection", "conn_exhaust"]),
    ("Silent data faults", ["silent_drop_payments", "silent_drop_orders", "sync_corruption", "queue_overflow"]),
    ("Unfixable fault (the agent must escalate)", ["unfixable_credentials"]),
    ("Hangs", ["hung_backend", "hung_exhaust"]),
]
METHODS = [("naive", "Naive restart"), ("runbook", "Fixed runbook"), ("agent", "Mend agent")]


def load():
    rows = json.loads((ROOT / "results" / "recovery_eval.json").read_text(encoding="utf-8"))
    return [r for r in rows if "error" not in r]


def cell(rows, scenario, method):
    mine = [r for r in rows if r["scenario"] == scenario and r["method"] == method]
    if not mine:
        return "-"
    ok = sum(bool(r["recovered"]) for r in mine)
    return "%d/%d" % (ok, len(mine))


def totals(rows, scenarios, method):
    mine = [r for r in rows if r["scenario"] in scenarios and r["method"] == method]
    ok = sum(bool(r["recovered"]) for r in mine)
    wrong = sum(r.get("wrong_actions", 0) or 0 for r in mine)
    tok = [r["tokens"] for r in mine if r.get("tokens")]
    return ok, len(mine), wrong, (sum(tok) / len(tok) if tok else 0)


def summary(rows):
    out = ["| Fault family | Naive restart | Fixed runbook | Mend agent | Agent wrong actions | Agent tokens per run |",
           "|---|---|---|---|---|---|"]
    for title, scenarios in GROUPS:
        n, r, a = (totals(rows, scenarios, m) for m in ("naive", "runbook", "agent"))
        out.append("| %s | %d/%d | %d/%d | **%d/%d** | %d | %s |" % (
            title, n[0], n[1], r[0], r[1], a[0], a[1], a[2], "{:,.0f}".format(a[3]) if a[3] else "-"))
    return "\n".join(out)


def detail(rows):
    out = []
    for title, scenarios in GROUPS:
        out += ["## " + title, "", "| Scenario | Naive restart | Fixed runbook | Mend agent | Wrong actions | Tokens per run |",
                "|---|---|---|---|---|---|"]
        for s in scenarios:
            mine = [r for r in rows if r["scenario"] == s and r["method"] == "agent"]
            wrong = sum(r.get("wrong_actions", 0) or 0 for r in mine)
            tok = [r["tokens"] for r in mine if r.get("tokens")]
            out.append("| %s | %s | %s | %s | %d | %s |" % (s, cell(rows, s, "naive"), cell(rows, s, "runbook"),
                                                        cell(rows, s, "agent"), wrong,
                                                        "{:,.0f}".format(sum(tok) / len(tok)) if tok else "-"))
        out.append("")
    fz = sorted({r["scenario"] for r in rows if r["scenario"].startswith("fz-")})
    extra = sorted({r["scenario"] for r in rows} - {s for _, g in GROUPS for s in g} - set(fz))
    out += ["Also recorded: %d fuzzer-generated faults and %d extra faults, mostly baselines only. See results/recovery_eval.json."
            % (len(fz), len(extra)), ""]
    return "\n".join(out)


def main():
    rows = load()
    block = summary(rows)
    (ROOT / "docs" / "RESULTS.md").write_text(
        "# Results\n\nGenerated by scripts/make_results.py from results/recovery_eval.json. Every saved run is counted.\n\n"
        "## Summary\n\n" + block + "\n\n" + detail(rows), encoding="utf-8")
    new = "<!-- RESULTS:START -->\n" + block + "\n<!-- RESULTS:END -->"
    for name in ("README.md", "docs/REPORT.md"):
        path = ROOT / name
        text = path.read_text(encoding="utf-8")
        text, n = re.subn(r"<!-- RESULTS:START -->.*?<!-- RESULTS:END -->", lambda m: new, text, flags=re.S)
        if n:
            path.write_text(text, encoding="utf-8")
    print(block)


if __name__ == "__main__":
    main()
